#!/usr/bin/env python3
"""Convert dhepper/font8x8's font8x8_basic.h into C arrays the engine's
text renderer consumes.

Usage: python3 tools/font8x8_convert.py <font8x8_basic.h> <output-base>

Outputs <output-base>.h and <output-base>.c containing:

  - the printable-ASCII slice (chars 32..126, 95 glyphs) of the source
    font, one packed byte per row, MSB-left (bit 7 = leftmost pixel,
    set bit = ink), glyphs laid out glyph-major: exactly the format
    documented above atma_font in include/atma/gfx.h;

  - a ready-to-pass atma_font instance wiring that array up with
    first=32, count=95 and the 8x8 cell.

The source font stores each row LSB-left (bit 0 = leftmost pixel), the
one convention the engine's format deliberately does not share; the
whole conversion is reversing the 8 bits of every row byte. The engine
format exists so C64/Spectrum/Atari charset dumps and font editor
exports land byte-identical, and font8x8 (LSB-left) is the documented
outlier that gets converted instead.

The vendored source header is the hand-edited-after-clone artifact:
keep it verbatim, attribution and public-domain notice intact, and
rerun this tool after replacing it. The generated files are machine
written; edit the tool or the source, never the output.

Nothing here knows about SDL or z88dk: the same arrays compile for
every backend. Requires Python 3 only (stdlib).
"""

import os
import re
import sys

FIRST = 32   # Char code of glyphs[0]; 32 = space.
LAST = 126   # Last printable ASCII char (~).
COUNT = LAST - FIRST + 1   # 95 glyphs, the printable-ASCII slice.
ROWS = 8     # Source cell height; the source is fixed 8x8.

ROW_BYTES = re.compile(r"0x([0-9A-Fa-f]+)")
CODEPOINT = re.compile(r"U\+([0-9A-Fa-f]{4})")


def die(msg):
    print(f"font8x8_convert: {msg}", file=sys.stderr)
    sys.exit(1)


def to_msb(b):
    """Reverse a byte's bit order: the source font stores rows LSB-left
    (bit 0 = leftmost pixel), the engine's format is MSB-left."""
    r = 0
    for _ in range(8):
        r = (r << 1) | (b & 1)
        b >>= 1
    return r


def read_glyphs(path):
    """Parse font8x8_basic.h into a list of 128 glyphs, 8 row bytes each.

    The array is extremely regular (one '{ 0x.., ... }' per line, the
    codepoint in a trailing comment), so a per-line scan with cross
    checks is a full parse; anything off-format fails loudly.
    """
    glyphs = []
    try:
        lines = open(path).read().splitlines()
    except OSError as e:
        die(str(e))
    for n, line in enumerate(lines, 1):
        code, _, comment = line.partition("//")
        if "{" not in code:
            continue
        vals = ROW_BYTES.findall(code)
        if not vals:
            continue
        if len(vals) != ROWS:
            die(f"{path}:{n}: expected {ROWS} row bytes, found {len(vals)}")
        bytes_ = [int(v, 16) for v in vals]
        for v in bytes_:
            if v > 255:
                die(f"{path}:{n}: row byte 0x{v:X} does not fit u8")
        cp = CODEPOINT.search(comment)
        if cp and int(cp.group(1), 16) != len(glyphs):
            die(f"{path}:{n}: comment says U+{cp.group(1)} but this is "
                f"glyph {len(glyphs)}")
        glyphs.append(bytes_)
    if len(glyphs) != 128:
        die(f"{path}: expected 128 glyphs, found {len(glyphs)}")
    return glyphs


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    if len(args) != 2:
        die(f"usage: {sys.argv[0]} <font8x8_basic.h> <output-base>")
    src, out_base = args

    glyphs = read_glyphs(src)

    stem = os.path.basename(out_base)
    # C identifiers: letters, digits, underscore, not starting with a
    # digit. Anything else in the file name (dash, space, dot) becomes
    # an underscore, and a leading digit gets a second one. (mkpats
    # convention.)
    ident = re.sub(r"\W", "_", stem)
    if ident[0].isdigit():
        ident = "_" + ident
    guard = ident.upper() + "_H"

    # The slice: printable ASCII, bit-reversed to the engine's MSB-left.
    rows = []
    for c in range(FIRST, LAST + 1):
        rows.append([to_msb(b) for b in glyphs[c]])

    h_path = out_base + ".h"
    c_path = out_base + ".c"

    with open(h_path, "w") as f:
        f.write(f"""/* Generated by tools/font8x8_convert.py from {src};
 * do not edit by hand. Rerun the tool after changing the source font
 * instead. Source font: dhepper/font8x8 (public domain). */

#ifndef {guard}
#define {guard}

#include "atma/gfx.h"

/* The printable-ASCII slice (chars {FIRST}..{LAST}, {COUNT} glyphs) of the
 * 128-glyph source, one packed byte per row, MSB-left (bit 7 =
 * leftmost pixel), glyphs laid out glyph-major: the format documented
 * above atma_font in include/atma/gfx.h. The source font is LSB-left;
 * this tool reverses every row byte. */
extern const atma_font {ident};

#endif
""")

    with open(c_path, "w") as f:
        f.write(f"""/* Generated by tools/font8x8_convert.py from {src};
 * do not edit by hand. Source font: dhepper/font8x8 (public domain). */

#include "{stem}.h"

static const unsigned char {ident}_glyphs[{COUNT} * {ROWS}] = {{
""")
        for i, row in enumerate(rows):
            f.write(f"    /* {FIRST + i} '{chr(FIRST + i)}' */\n")
            f.write("    " + ", ".join(f"0x{b:02X}" for b in row) + ",\n")
        f.write(f"""}};

const atma_font {ident} = {{
    .glyphs = {ident}_glyphs,
    .first = {FIRST},
    .count = {COUNT},
    .w = 8,
    .h = {ROWS}
}};
""")

    print(f"{src}: 128 glyphs, sliced to ASCII {FIRST}..{LAST} "
          f"({COUNT} glyphs, MSB-left) -> {h_path}, {c_path}")


if __name__ == "__main__":
    main()
